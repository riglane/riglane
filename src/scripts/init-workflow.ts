export function initWorkflowSync(
  name: string,
  opts: InitWorkflowOptions = {},
): InitWorkflowResult {
  const r = resolveOpts(opts);
  const [wfPath, workflow] = loadWorkflow(name, r.cwd);

  if (workflow === null || typeof workflow !== 'object' || Array.isArray(workflow)) {
    throw new WorkflowMalformedError(`workflow.yaml is not a mapping: ${wfPath}`);
  }

  const wfName = (workflow.name as string | undefined) || name;
  r.stdout(`Workflow: ${wfName} (${wfPath})\n`);

  const subSteps = subagentSteps(workflow);
  if (subSteps.length === 0) {
    r.stdout('  No subagent steps. Nothing to generate.\n');
    return { created: [], updated: [], unchanged: [], deleted: [], total: 0 };
  }

  const { hasOpencode, hasCopilot, hasGemini, genClaude } = detectAgentFileHosts(r.cwd);

  const created: string[] = [];
  const updated: string[] = [];
  const unchanged: string[] = [];
  const deleted: string[] = [];

  const record = (status: WriteStatus, name: string): void => {
    if (status === 'created') {
      created.push(name);
      r.stdout(`  CREATED  ${name}\n`);
    } else if (status === 'updated') {
      updated.push(name);
      r.stdout(`  UPDATED  ${name}\n`);
    } else {
      unchanged.push(name);
      r.stdout(`  UNCHANGED ${name}\n`);
    }
  };

  const agentProfiles = (step: Record<string, unknown>): AgentProfile[] =>
    Object.entries(stepBranchProfiles(step) ?? {}).map(([id, def]) => ({ id, def }));

  if (genClaude) {
    const expectedDirNames: string[] = [];
    for (const [stepName, step] of subSteps) {
      if (!stepName) {
        r.stderr('WARNING: step without name; skipping\n');
        continue;
      }
      const [status, dirName] = writeSubagent(workflow, step, opts);
      expectedDirNames.push(dirName);
      record(status, dirName);
      for (const profile of agentProfiles(step)) {
        const [pStatus, pDirName] = writeSubagent(workflow, step, opts, profile);
        expectedDirNames.push(pDirName);
        record(pStatus, pDirName);
      }
    }

    const orphans = findOrphanSubagents(wfName, expectedDirNames, opts);
    for (const orphan of orphans) {
      deleteOrphan(orphan, opts);
      deleted.push(orphan);
      r.stdout(`  DELETED  ${orphan} (orphan)\n`);
    }
  }

  if (hasOpencode) {
    const expectedAgentNames: string[] = [];
    for (const [stepName, step] of subSteps) {
      if (!stepName) {
        if (!genClaude) r.stderr('WARNING: step without name; skipping\n');
        continue;
      }
      const [status, agentName] = writeOpencodeSubagent(workflow, step, opts);
      expectedAgentNames.push(agentName);
      record(status, `${agentName}.md`);
      for (const profile of agentProfiles(step)) {
        const [pStatus, pName] = writeOpencodeSubagent(workflow, step, opts, profile);
        expectedAgentNames.push(pName);
        record(pStatus, `${pName}.md`);
      }
    }

    const ocOrphans = findOrphanOpencodeSubagents(wfName, expectedAgentNames, opts);
    for (const orphan of ocOrphans) {
      deleteOpencodeOrphan(orphan, opts);
      deleted.push(`${orphan}.md`);
      r.stdout(`  DELETED  ${orphan}.md (orphan)\n`);
    }
  }

  if (hasCopilot) {
    const expectedAgentNames: string[] = [];
    for (const [stepName, step] of subSteps) {
      if (!stepName) {
        if (!genClaude && !hasOpencode) r.stderr('WARNING: step without name; skipping\n');
        continue;
      }
      const [status, agentName] = writeCopilotSubagent(workflow, step, opts);
      expectedAgentNames.push(agentName);
      record(status, `${agentName}.agent.md`);
      for (const profile of agentProfiles(step)) {
        const [pStatus, pName] = writeCopilotSubagent(workflow, step, opts, profile);
        expectedAgentNames.push(pName);
        record(pStatus, `${pName}.agent.md`);
      }
    }

    const cpOrphans = findOrphanCopilotSubagents(wfName, expectedAgentNames, opts);
    for (const orphan of cpOrphans) {
      deleteCopilotOrphan(orphan, opts);
      deleted.push(`${orphan}.agent.md`);
      r.stdout(`  DELETED  ${orphan}.agent.md (orphan)\n`);
    }
  }

  if (hasGemini) {
    const expectedAgentNames: string[] = [];
    for (const [stepName, step] of subSteps) {
      if (!stepName) {
        if (!genClaude && !hasOpencode && !hasCopilot)
          r.stderr('WARNING: step without name; skipping\n');
        continue;
      }
      const [status, agentName] = writeGeminiSubagent(workflow, step, opts);
      expectedAgentNames.push(agentName);
      record(status, `${agentName}.md`);
      for (const profile of agentProfiles(step)) {
        const [pStatus, pName] = writeGeminiSubagent(workflow, step, opts, profile);
        expectedAgentNames.push(pName);
        record(pStatus, `${pName}.md`);
      }
    }

    const gmOrphans = findOrphanGeminiSubagents(wfName, expectedAgentNames, opts);
    for (const orphan of gmOrphans) {
      deleteGeminiOrphan(orphan, opts);
      deleted.push(`${orphan}.md`);
      r.stdout(`  DELETED  ${orphan}.md (orphan)\n`);
    }

    const acked = ackGeminiAgents(r.cwd, { dryRun: r.dryRun });
    if (acked.length > 0) {
      r.stdout(`  ACK      ${acked.length} gemini agent(s) acknowledged (headless consent)\n`);
    }
  }

  const total = created.length + updated.length + deleted.length;
  r.stdout('\n');
  r.stdout(
    `Summary: ${created.length} created, ${updated.length} updated, ` +
      `${unchanged.length} unchanged, ${deleted.length} deleted\n`,
  );

  if (total > 0) {
    const hosts = agentFileHostLabels(r.cwd);
    r.stdout('\n');
    r.stdout(`[!] Restart ${hosts.join(' / ')} to load the new/updated subagents.\n`);
    r.stdout(`    After restart, you can run: /riglane-run-workflow ${wfName}\n`);
  }

  return { created, updated, unchanged, deleted, total };
}

export async function initWorkflow(
  name: string,
  opts: InitWorkflowOptions = {},
): Promise<InitWorkflowResult> {
  return initWorkflowSync(name, opts);
}

export async function runInitWorkflowCli(
  argv: string[] = process.argv.slice(2),
  opts: InitWorkflowOptions = {},
): Promise<number> {
  const r = resolveOpts(opts);
  let parsed: { values: Record<string, string | boolean | undefined>; positionals: string[] };
  try {
    parsed = parseArgs({
      args: argv,
      options: { 'dry-run': { type: 'boolean' as const } },
      allowPositionals: true,
      strict: true,
    }) as { values: Record<string, string | boolean | undefined>; positionals: string[] };
  } catch (e) {
    r.stderr(`${e instanceof Error ? e.message : String(e)}\n`);
    return 2;
  }

  const name = parsed.positionals[0];
  if (!name) {
    r.stderr('usage: init-workflow <workflow-name> [--dry-run]\n');
    return 2;
  }
  if (parsed.positionals.length > 1) {
    r.stderr(`init-workflow: unrecognized arguments: ${parsed.positionals.slice(1).join(' ')}\n`);
    return 2;
  }

  const dryRun = Boolean(parsed.values['dry-run']);
  try {
    await initWorkflow(name, { ...opts, dryRun });
    return 0;
  } catch (e) {
    r.stderr(`ERROR: ${e instanceof Error ? e.message : String(e)}\n`);
    if (e instanceof WorkflowNotFoundError) return 1;
    if (e instanceof WorkflowMalformedError) return 2;
    if (e instanceof WorkflowFileWriteError) return 3;
    return 1;
  }
}
