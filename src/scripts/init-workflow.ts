export interface AgentProfile {
  readonly id: string;
  readonly def: BranchProfile;
}

function profileSuffix(profile?: AgentProfile): string {
  return profile !== undefined ? `--${profile.id}` : '';
}

function effectiveStep(
  step: Record<string, unknown>,
  profile?: AgentProfile,
): Record<string, unknown> {
  return profile !== undefined ? profileNarrowedStep(step, profile.def) : step;
}

function agentDescription(stepName: string, wfName: string, profile?: AgentProfile): string {
  const profileClause = profile !== undefined ? `, branch profile '${profile.id}'` : '';
  return `Workflow step subagent for '${stepName}' step of '${wfName}' workflow${profileClause}. Auto-generated — do not edit manually.`;
}

function agentOpeningLine(stepName: string, wfName: string, profile?: AgentProfile): string {
  const profileClause =
    profile !== undefined ? `, as its '${profile.id}' branch profile` : '';
  return `You are executing step '${stepName}' of workflow '${wfName}'${profileClause}.`;
}


