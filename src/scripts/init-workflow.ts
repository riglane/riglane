export function subagentSteps(workflow: WorkflowDoc): Array<[string, Record<string, unknown>]> {
  const out: Array<[string, Record<string, unknown>]> = [];
  for (const step of collectAllSteps({ steps: workflow.steps })) {
    if (step.subagent !== false) {
      const name = (step.name as string | undefined) ?? '';
      out.push([name, step]);
    }
  }
  return out;
}


