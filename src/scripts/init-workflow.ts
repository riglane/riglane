export interface InitWorkflowOptions {
  readonly dryRun?: boolean;
  readonly cwd?: string;
  readonly stdout?: (s: string) => void;
  readonly stderr?: (s: string) => void;
  readonly modelOverride?: string;
}

interface ResolvedOptions {
  readonly dryRun: boolean;
  readonly cwd: string;
  readonly stdout: (s: string) => void;
  readonly stderr: (s: string) => void;
  readonly modelOverride?: string;
}

function resolveOpts(opts: InitWorkflowOptions = {}): ResolvedOptions {
  return {
    dryRun: opts.dryRun ?? false,
    cwd: opts.cwd ?? '.',
    stdout: opts.stdout ?? ((s: string) => void process.stdout.write(s)),
    stderr: opts.stderr ?? ((s: string) => void process.stderr.write(s)),
    ...(opts.modelOverride ? { modelOverride: opts.modelOverride } : {}),
  };
}


export function loadWorkflow(name: string, cwd = '.'): [string, WorkflowDoc] {
  const candidates = [
    join(cwd, TEMPLATES_DIR, 'my_workflows', name, 'workflow.yaml'),
    join(cwd, TEMPLATES_DIR, 'predefined', name, 'workflow.yaml'),
    join(cwd, TEMPLATES_DIR, 'examples', name, 'workflow.yaml'),
    join(cwd, TEMPLATES_DIR, 'community', name, 'workflow.yaml'),
    join(cwd, WORKFLOWS_DIR, name, 'workflow.yaml'),
  ];
  for (const path of candidates) {
    if (existsSync(path) && statSync(path).isFile()) {
      try {
        const data = loadYaml<WorkflowDoc>(path);
        return [path, data];
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        throw new WorkflowMalformedError(`failed to parse workflow.yaml: ${msg}`);
      }
    }
  }
  throw new WorkflowNotFoundError(
    `Workflow '${name}' not found. Searched:\n  ${candidates.join('\n  ')}`,
  );
}


