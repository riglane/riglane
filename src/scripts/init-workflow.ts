export function writeOpencodeSubagent(
  workflow: WorkflowDoc,
  step: Record<string, unknown>,
  opts: InitWorkflowOptions = {},
  profile?: AgentProfile,
): [WriteStatus, string] {
  const r = resolveOpts(opts);
  const wfName = (workflow.name as string | undefined) ?? '';
  const stepName = (step.name as string | undefined) ?? '';
  const agentName = `${opencodeAgentName(wfName, stepName)}${profileSuffix(profile)}`;
  const agentsDir = join(r.cwd, OPENCODE_AGENTS_DIR);
  const agentPath = join(agentsDir, `${agentName}.md`);

  const newContent = buildOpencodeAgentMd(workflow, step, profile);

  let existingContent: string | null = null;
  if (existsSync(agentPath) && statSync(agentPath).isFile()) {
    try {
      existingContent = readFileSync(agentPath, 'utf-8');
    } catch {
      existingContent = null;
    }
  }

  if (existingContent === newContent) {
    return ['unchanged', agentName];
  }

  const status: WriteStatus = existingContent !== null ? 'updated' : 'created';

  if (!r.dryRun) {
    try {
      mkdirSync(agentsDir, { recursive: true });
      writeFileSync(agentPath, newContent, 'utf-8');
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      throw new WorkflowFileWriteError(`failed to write opencode subagent for ${stepName}: ${msg}`);
    }
  }

  return [status, agentName];
}

export function findOrphanOpencodeSubagents(
  workflowName: string,
  expectedNames: readonly string[],
  opts: InitWorkflowOptions = {},
): string[] {
  const r = resolveOpts(opts);
  const agentsDir = join(r.cwd, OPENCODE_AGENTS_DIR);
  if (!existsSync(agentsDir) || !statSync(agentsDir).isDirectory()) return [];

  const prefix = `${AGENT_PREFIX}${workflowName}-`;
  const expected = new Set(expectedNames);
  const found: string[] = [];

  const entries = readdirSync(agentsDir, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
    const agentName = entry.name.slice(0, -'.md'.length);
    if (!agentName.startsWith(prefix)) continue;
    if (expected.has(agentName)) continue;

    let content: string;
    try {
      content = readFileSync(join(agentsDir, entry.name), 'utf-8');
    } catch {
      continue;
    }
    if (content.includes(GENERATED_MARKER)) {
      found.push(agentName);
    }
  }
  return found.sort();
}

export function deleteOpencodeOrphan(name: string, opts: InitWorkflowOptions = {}): void {
  const r = resolveOpts(opts);
  const agentPath = join(r.cwd, OPENCODE_AGENTS_DIR, `${name}.md`);
  if (r.dryRun) return;
  try {
    if (existsSync(agentPath) && statSync(agentPath).isFile()) {
      unlinkSync(agentPath);
    }
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    r.stderr(`Failed to delete ${agentPath}: ${msg}\n`);
  }
}

